-- -- EXPERIMENT: BANKING TRANSACTIONS AND CONCURRENCY CONTROL

-- 1. CREATE DATABASE
CREATE DATABASE BankingDB;
USE BankingDB;

-- 2. CREATE ACCOUNTS TABLE
CREATE TABLE Accounts (
    Account_ID INT PRIMARY KEY,
    Account_Name VARCHAR(50),
    Balance DECIMAL(10,2)
) ENGINE = InnoDB;

INSERT INTO Accounts VALUES
(101, 'Rahul', 10000),
(102, 'Priya', 8000),
(103, 'Amit', 5000);

SELECT * FROM Accounts;


-- 3. BEGIN AND COMMIT
START TRANSACTION;

UPDATE Accounts
SET Balance = Balance - 2000
WHERE Account_ID = 101;

UPDATE Accounts
SET Balance = Balance + 2000
WHERE Account_ID = 102;

COMMIT;

SELECT * FROM Accounts;


-- 4. ROLLBACK
START TRANSACTION;

UPDATE Accounts
SET Balance = Balance - 1000
WHERE Account_ID = 101;

UPDATE Accounts
SET Balance = Balance + 1000
WHERE Account_ID = 103;

ROLLBACK;

SELECT * FROM Accounts;


-- 5. SAVEPOINT
START TRANSACTION;

UPDATE Accounts
SET Balance = Balance - 3000
WHERE Account_ID = 101;

SAVEPOINT S1;

UPDATE Accounts
SET Balance = Balance + 3000
WHERE Account_ID = 102;

ROLLBACK TO S1;

UPDATE Accounts
SET Balance = Balance + 3000
WHERE Account_ID = 103;

COMMIT;

SELECT * FROM Accounts;


-- 6. SIMULATE PARTIAL FAILURE
START TRANSACTION;

UPDATE Accounts
SET Balance = Balance - 2000
WHERE Account_ID = 101;

SAVEPOINT After_Debit;

-- Invalid account: no row will be updated
UPDATE Accounts
SET Balance = Balance + 2000
WHERE Account_ID = 999;

ROLLBACK TO After_Debit;

Correct the failed operation
UPDATE Accounts
SET Balance = Balance + 2000
WHERE Account_ID = 102;

COMMIT;

SELECT * FROM Accounts;


-- 7. READ UNCOMMITTED
SET SESSION TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;

START TRANSACTION;

SELECT * FROM Accounts;

COMMIT;


-- 8. READ COMMITTED
SET SESSION TRANSACTION ISOLATION LEVEL READ COMMITTED;

START TRANSACTION;

SELECT * FROM Accounts;

COMMIT;


-- 9. REPEATABLE READ
SET SESSION TRANSACTION ISOLATION LEVEL REPEATABLE READ;

START TRANSACTION;

SELECT * FROM Accounts;

COMMIT;


-- 10. SERIALIZABLE
SET SESSION TRANSACTION ISOLATION LEVEL SERIALIZABLE;

START TRANSACTION;

SELECT * FROM Accounts;

COMMIT;

-- 11. DEMONSTRATE PHANTOM READ
SET SESSION TRANSACTION ISOLATION LEVEL READ COMMITTED;

START TRANSACTION;

SELECT * FROM Accounts
WHERE Balance > 5000;

COMMIT;


-- 12. FINAL ACCOUNT DETAILS
SELECT * FROM Accounts;

SET SESSION TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;

START TRANSACTION;

UPDATE Accounts
SET Balance = 15000
WHERE Account_ID = 101;

-- -- Keep transaction open

SET SESSION TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;

START TRANSACTION;

SELECT * FROM Accounts
WHERE Account_ID = 101;

COMMIT;

ROLLBACK;